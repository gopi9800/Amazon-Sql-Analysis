-- 2.Revenue by category
-- caliculate total revenue generated by each product category.
-- challenge:Include the percentage contribution of each category to total revenue

select p.category_id,c.category_name,sum(oi.total_sale) 
as total_sale,sum(oi.total_sale) / (select sum(total_sale) from order_items) * 100 as contribution
from order_items as oi join products as p
on oi.product_id = p.product_id
left join category as c 
on c.category_id = p.category_id
group by 1,2 order by 3 desc;


-- 3.Average Order Value(AOV)
-- Compute the average order value for each customer

SELECT
    c.customer_id,
    CONCAT(c.first_name, ' ', c.last_name) AS full_name,
    SUM(total_sale) / COUNT(o.order_id) AS AOV,
    COUNT(o.order_id) AS total_orders -- filter
FROM orders AS o
JOIN customers AS c
    ON c.customer_id = o.customer_id
JOIN order_items AS oi
    ON oi.order_id = o.order_id
GROUP BY 1, 2
HAVING count(o.order_id) > 5;


/*
4. Monthly Sales Trend
Query monthly total sales over the past year.
Challenge: Display the sales trend, grouping by month, return current_month sale, last month sale!
*/


select year,month,total_sale as current_total_sale,lag(total_sale,1) over (order by year,month) as last_month_sale from
(select extract(year from o.order_date) as year,extract(month from o.order_date) as month,
round(sum(oi.total_sale::numeric),2) as total_sale from orders as o join order_items as oi
on o.order_id = oi.order_id where o.order_date > current_date - interval '3 years'
group by 1,2 order by year,month) as t1

