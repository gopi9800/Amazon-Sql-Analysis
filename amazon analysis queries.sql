-- 11.Top performaing seller
-- Find the top 5 sellers based on total sales value
-- challenge:Include both successful and failed orders and display their percentage of successful orders.


with top_sellers as (
select s.seller_id,s.seller_name,sum(total_sale) as total_sale from seller as s
join orders as o on s.seller_id = o.seller_id
join order_items as oi on oi.order_id = o.order_id
group by 1,2 order by 3 desc limit 5
),
sellers_reports AS (
    SELECT 
        o.seller_id,
        ts.seller_name,
        o.order_status,
        COUNT(*) AS order_count
    FROM orders o
    JOIN top_sellers ts 
        ON ts.seller_id = o.seller_id
		where order_status not in ('Pending','Returned')
    GROUP BY 1, 2, 3
)
SELECT seller_id,seller_name,
SUM(CASE WHEN ORDER_STATUS = 'Delivered' THEN order_count ELSE 0 END) AS delivered_orders,
SUM(CASE WHEN ORDER_STATUS = 'Cancelled' THEN order_count ELSE 0 END) AS cancelled_orders,
sum(order_count)
FROM sellers_reports
GROUP BY 1,2
ORDER BY 1;


-- 12.Most returned products
-- Query the top 10 products by the number of returns.
-- challenge:Display the return rate as percentage of total units sold for each product

select p.product_id,p.product_name,count(*) as total_units_sold,
sum(case when o.order_status = 'Returned' then 1 else 0 end) as total_returned,
round(sum(case when o.order_status = 'Returned' then 1 else 0 end)::numeric / count(*) ::numeric * 100,2) as returned_percentage
