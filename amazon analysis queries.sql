-- 13.Inactive Sellers
-- Identify sellers who have not made any sales in last 6 months
-- challenge:show the last sale date and total sales from those sellers


with cte as (
select * from seller where seller_id not in 
(select seller_id from orders where order_date > current_date - interval '1 year')
)

select o.seller_id,max(o.order_date) as last_order_date,
max(oi.total_sale) as last_sale_amount from orders as o
join order_items as oi on o.order_id = oi.order_id
join cte on cte.seller_id = o.seller_id
group by 1


-- 14.Identify customers into returning or new if the customer has done more than 
-- 5 return categoorize them as returning otherwise new
-- challenge:list customers id,name,total orders,total returns

with cte as (
select concat(c.first_name,' ',c.last_name) as full_name,sum(o.order_id)  as total_orders,
sum(case when o.order_status = 'Returned' then 1 else 0 end) as total_returned from orders as o
join order_items as oi on o.order_id = oi.order_id
join customers as c on c.customer_id = o.customer_id
group by 1
)
select cte.*,case when total_returned > 5 then 'Returned' else 'New' end as customer_category from cte


