-- 17.Top 10 products with highest decreasing revenue ratio compared to last year and current year
-- challenge:Return product_id,product_name,category_name,2024 revenue and 2025 revenue decrease
-- ratio at the end of result


with last_year as (
select p.product_id,p.product_name,sum(oi.total_sale) as revenue from orders as o
join order_items as oi on o.order_id = oi.order_id
join products as p on p.product_id = oi.product_id
where extract(year from o.order_date) = 2022
group by 1,2),


current_year as (
select p.product_id,p.product_name,sum(oi.total_sale) as revenue from orders as o
join order_items as oi on o.order_id = oi.order_id
join products as p on p.product_id = oi.product_id
where extract(year from o.order_date) = 2023
group by 1,2)


select cs.product_id,ls.revenue as last_year_revenue,
cs.revenue - ls.revenue as revenue_difference,
round((cs.revenue - ls.revenue)::numeric / ls.revenue::numeric * 100,2) as revenue_diff_ratio,
cs.revenue as current_year_revenue from last_year as ls
join current_year as cs on ls.product_id = cs.product_id
where ls.revenue > cs.revenue
order by revenue_diff_ratio desc limit 5


